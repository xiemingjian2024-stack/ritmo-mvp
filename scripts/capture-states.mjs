import { chromium } from "@playwright/test";
import fs from "node:fs/promises";
const root = new URL("../", import.meta.url).pathname;
const out = `${root}evidence`;
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1400, height: 1200 }, deviceScaleFactor: 1 });
await page.goto("http://127.0.0.1:4173/?flow=training");
const screen = page.getByTestId("device-screen");
await screen.waitFor({ state: "visible" });
await page.waitForTimeout(7600);
await screen.screenshot({ path: `${out}/training-rest.png` });
await page.getByRole("button", { name: /^下一组/ }).click();
await page.waitForTimeout(250);
await screen.screenshot({ path: `${out}/training-rest-edit.png` });
await page.goto("http://127.0.0.1:4173/?flow=plans");
await page.getByRole("button", { name: /自行添加动作/ }).click();
await page.waitForTimeout(250);
await screen.screenshot({ path: `${out}/plans-sheet.png` });
await browser.close();
console.log(out);
